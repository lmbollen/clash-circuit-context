'Integer' and 'Natural' as Clash's hardware carries them: 64 bits, two's
complement for 'Integer'. The recorders pack a traced or probed @Integer@
through 'Integer64' (see @$integer@ in "Clash.CircuitContext.Auto").

A module of their own because their 'BitPack' instances are generated by a
Template Haskell splice ('withMaybeUnpack'), and a splice ends a declaration
group: in "Clash.CircuitContext.Auto" it would cut the module in two.
-}
module Clash.CircuitContext.Internal.Wide64 (Integer64 (..), Natural64 (..)) where

import Clash.Prelude (BitPack (..), NFDataX)
import Clash.Shockwaves.Waveform (
  DecSpacer,
  NumberFormat (NFSig, NFUns),
  Waveform,
  WaveformForNumber (..),
 )
import Data.Int (Int64)
import Data.Word (Word64)
import Numeric.Natural (Natural)

import Clash.CircuitContext.Internal.BitPackCompat (withMaybeUnpack)

-- | 'Integer' as Clash's hardware carries it.
newtype Integer64 = Integer64 Integer
  deriving newtype (NFDataX)

-- | 'Natural' as Clash's hardware carries it.
newtype Natural64 = Natural64 Natural
  deriving newtype (NFDataX)

withMaybeUnpack
  [d|
    instance BitPack Integer64 where
      type BitSize Integer64 = 64
      pack (Integer64 i) = pack (fromInteger i :: Int64)
      unpack = Integer64 . toInteger . unpack @Int64

    instance BitPack Natural64 where
      type BitSize Natural64 = 64
      pack (Natural64 n) = pack (fromIntegral n :: Word64)
      unpack = Natural64 . fromIntegral . unpack @Word64
    |]

deriving via
  WaveformForNumber 'NFSig DecSpacer Integer64
  instance
    Waveform Integer64

deriving via
  WaveformForNumber 'NFUns DecSpacer Natural64
  instance
    Waveform Natural64
